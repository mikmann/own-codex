pub fn plan_turn_with_history(
    input: &str,
    history: &[codex_protocol::models::ResponseItem],
    turn_id: &str,
    config: &ExtendedWorkflowConfig,
) -> WorkflowTurnPlan {
    plan_turn_for_binding(resolve_task_binding(input, history), turn_id, config)
}

fn plan_turn_for_binding(
    binding: WorkflowTaskBinding,
    turn_id: &str,
    config: &ExtendedWorkflowConfig,
) -> WorkflowTurnPlan {
    let effective_request = binding.effective_request;
    let classification = workflow_type::apply_to_classification(
        classify_request(&effective_request),
        config.workflow_type,
    );
    let root_request_sha256 = sha256_bytes(effective_request.as_bytes());
    let task_binding_blocked = effective_request.len() > MAX_WORKFLOW_ROOT_REQUEST_BYTES;
    let task_binding_message = task_binding_blocked.then(|| {
        format!(
            "root request is {} UTF-8 bytes; the server-bound workflow limit is {MAX_WORKFLOW_ROOT_REQUEST_BYTES}. Split the request into a smaller independently verifiable ticket before starting subagents",
            effective_request.len()
        )
    });
    let task_binding_message = task_binding_message.or(binding.message);
    let requires_concept_artifact = classification.class == RequestClass::WorkOrder
        && count_lexical_signals(
            &lexical_tokens(&effective_request.to_lowercase()),
            &[
                "konzept",
                "entwurf",
                "architekturvorschlag",
                "concept",
                "strategie",
                "strategy",
                "roadmap",
                "planung",
            ],
            &[],
            &[&["design", "proposal"]],
        ) > 0;
    let needs_clarification = binding.kind == WorkflowTaskBindingKind::NeedsClarification;
    let desired_experts = if needs_clarification {
        0
    } else {
        desired_expert_count(&classification, &config.experts)
    };
    let experts = plan_process(
        &classification,
        &effective_request,
        WorkflowAgentKind::Expert,
        turn_id,
        &config.experts,
        desired_experts,
    );
    WorkflowTurnPlan {
        classification,
        task_binding_kind: binding.kind,
        effective_root_request: effective_request,
        root_request_sha256,
        task_binding_blocked,
        task_binding_message,
        requires_concept_artifact,
        experts,
        reviewer_policy_enabled: !needs_clarification
            && config.reviewers.enabled
            && config.reviewers.max > 0,
        reviewer_min: config.reviewers.min,
        reviewer_max: config.reviewers.max,
        advisory_workflow_budget: config.workflow_budget_tokens,
        budget_scope: "workflow_budget_tokens is a hard cumulative provider total-token ceiling shared by the main agent, experts, reviewers, and compactions; zero or omission means unlimited. It does not reduce the planned agent count. Per-profile and round budgets remain advisory pre-spawn estimates."
            .to_string(),
        audit_mode_enabled: config.audit_mode,
        audit_files_written: false,
    }
}

pub fn plan_reviewers(
    change_summary: &str,
    turn_id: &str,
    config: &ExtendedWorkflowConfig,
) -> WorkflowProcessPlan {
    let classification = classify_request(change_summary);
    let desired = desired_reviewer_count(&classification, &config.reviewers);
    plan_process(
        &classification,
        change_summary,
        WorkflowAgentKind::Reviewer,
        turn_id,
        &config.reviewers,
        desired,
    )
}

fn desired_expert_count(
    classification: &RequestClassification,
    process: &WorkflowProcessConfig,
) -> usize {
    if !process.enabled || process.max == 0 {
        return 0;
    }
    if classification.class == RequestClass::SimpleAnswer
        && classification.domains.len() < 2
        && classification.risk == RequestRisk::Routine
        && !classification.has_material_uncertainty
    {
        return 0;
    }
    dynamic_count(classification, process)
}

fn desired_reviewer_count(
    classification: &RequestClassification,
    process: &WorkflowProcessConfig,
) -> usize {
    if !process.enabled || process.max == 0 {
        0
    } else {
        dynamic_count(classification, process)
    }
}

fn dynamic_count(classification: &RequestClassification, process: &WorkflowProcessConfig) -> usize {
    let domain_pressure = classification.domains.len().saturating_sub(1);
    let risk_pressure = match classification.risk {
        RequestRisk::Routine => 0,
        RequestRisk::Elevated => 1,
        RequestRisk::High => 2,
    };
    let complexity_pressure = usize::from(classification.complexity_score >= 3)
        + usize::from(classification.complexity_score >= 5);
    process
        .min
        .saturating_add(domain_pressure)
        .saturating_add(risk_pressure)
        .saturating_add(complexity_pressure)
        .min(process.max)
}

fn plan_process(
    classification: &RequestClassification,
    selection_text: &str,
    kind: WorkflowAgentKind,
    turn_id: &str,
    process: &WorkflowProcessConfig,
    mut desired: usize,
) -> WorkflowProcessPlan {
    if !process.enabled || process.max == 0 || desired == 0 {
        return WorkflowProcessPlan {
            enabled: process.enabled,
            requested_count: 0,
            selected: Vec::new(),
            estimated_tokens: 0,
            advisory_round_budget: process.round_budget_tokens,
            budget_blocked: false,
            budget_message: None,
            change_digest_sha256: None,
        };
    }

    let effective_budget = process.round_budget_tokens;
    let mut budget_message = None;
    if let Some(budget) = effective_budget {
        while desired > process.min
            && estimated_tokens_for_selection(
                classification,
                selection_text,
                &process.profiles,
                desired,
            ) > budget
        {
            desired -= 1;
        }
        let minimum_estimate = estimated_tokens_for_selection(
            classification,
            selection_text,
            &process.profiles,
            process.min,
        );
        if minimum_estimate > budget {
            return WorkflowProcessPlan {
                enabled: true,
                requested_count: desired,
                selected: Vec::new(),
                estimated_tokens: minimum_estimate,
                advisory_round_budget: process.round_budget_tokens,
                budget_blocked: true,
                budget_message: Some(format!(
                    "advisory budget {budget} tokens is below the estimated {minimum_estimate} tokens required for the configured minimum of {} agents; no agent should be started",
                    process.min
                )),
                change_digest_sha256: None,
            };
        }
        if desired < dynamic_count(classification, process) {
            budget_message = Some(format!(
                "agent count reduced to {desired} before spawning to stay within the advisory budget of {budget} tokens"
            ));
        }
    }

    let selected_profiles =
        roles::select_profiles(classification, selection_text, &process.profiles, desired);
    let turn_key = sha256_bytes(turn_id.as_bytes());
    let turn_key = &turn_key[..12];
    let estimated_tokens = selected_profiles
        .iter()
        .map(|selection| estimated_profile_tokens(selection.profile))
        .fold(0, u64::saturating_add);
    WorkflowProcessPlan {
        enabled: true,
        requested_count: desired,
        selected: selected_profiles
            .into_iter()
            .enumerate()
            .map(|(index, selection)| WorkflowAgentPlan {
                task_name: format!(
                    "workflow_{}_{}_{}",
                    turn_key,
                    kind.label().to_ascii_lowercase(),
                    index + 1
                ),
                name: selection.profile.name.clone(),
                role: selection.profile.role.clone(),
                agent_type: selection.profile.agent_type.clone(),
                profile_source: selection.profile.source.label().to_string(),
                selection_reason: selection.selection_reason,
                matched_selection_keywords: selection.matched_keywords,
                role_source: None,
                role_fingerprint: None,
                role_preflight: WorkflowRolePreflightStatus::Pending,
                role_instruction_tokens: 0,
                role_fingerprint_sha256: None,
                model: selection.profile.model.clone(),
                reasoning_effort: selection.profile.reasoning_effort.clone(),
                token_budget: selection.profile.token_budget,
                context_budget: selection.profile.context_budget,
                read_only: true,
            })
            .collect(),
        estimated_tokens,
        advisory_round_budget: process.round_budget_tokens,
        budget_blocked: false,
        budget_message,
        change_digest_sha256: None,
    }
}

fn profile_matches_domain(profile: &str, domain: &str) -> bool {
    match domain {
        "architecture" => profile.contains("architect"),
        "security" => profile.contains("security") || profile.contains("sicherheit"),
        "testing" => profile.contains("test") || profile.contains("compatib"),
        "cli_ux" => {
            profile.contains("cli")
                || profile.contains("user experience")
                || profile.contains("documentation")
        }
        "data" => profile.contains("data") || profile.contains("database"),
        "concurrency" => {
            profile.contains("concurrency")
                || profile.contains("reliability")
                || profile.contains("performance")
        }
        _ => false,
    }
}

fn estimated_tokens_for_selection(
    classification: &RequestClassification,
    selection_text: &str,
    profiles: &[WorkflowAgentProfileConfig],
    count: usize,
) -> u64 {
    roles::select_profiles(classification, selection_text, profiles, count)
        .into_iter()
        .map(|selection| estimated_profile_tokens(selection.profile))
        .fold(0, u64::saturating_add)
}

fn estimated_profile_tokens(profile: &WorkflowAgentProfileConfig) -> u64 {
    profile
        .token_budget
        .unwrap_or(DEFAULT_ESTIMATED_AGENT_TOKENS)
}

fn lexical_tokens(text: &str) -> Vec<&str> {
    text.split(|character: char| !character.is_alphanumeric())
        .filter(|token| !token.is_empty())
        .collect()
}

fn count_lexical_signals(
    tokens: &[&str],
    exact: &[&str],
    prefixes: &[&str],
    phrases: &[&[&str]],
) -> usize {
    exact
        .iter()
        .filter(|signal| tokens.contains(signal))
        .count()
        + prefixes
            .iter()
            .filter(|prefix| tokens.iter().any(|token| token.starts_with(**prefix)))
            .count()
        + phrases
            .iter()
            .filter(|phrase| {
                tokens
                    .windows(phrase.len())
                    .any(|window| window == **phrase)
            })
            .count()
}

fn detect_domains(text: &str) -> Vec<String> {
    let candidates = [
        ("architecture", ["architektur", "architecture", "design"]),
        ("security", ["sicherheit", "security", "permission"]),
        ("testing", ["test", "quality", "kompatibilität"]),
        ("cli_ux", ["cli", "terminal", "ux"]),
        ("data", ["datenbank", "database", "migration"]),
        ("concurrency", ["nebenläufig", "concurrency", "parallel"]),
    ];
    candidates
        .into_iter()
        .filter(|(_, signals)| signals.iter().any(|signal| text.contains(signal)))
        .map(|(domain, _)| domain.to_string())
        .collect()
}

