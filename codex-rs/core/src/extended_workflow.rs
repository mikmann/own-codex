pub(crate) const WORKFLOW_RESULT_CONTRACT_MARKER: &str =
    "\n\n<extended_workflow_result_contract>\n";

pub(crate) fn require_bounded_workflow_text(
    label: &str,
    value: &str,
    max_bytes: usize,
) -> Result<(), String> {
    let bytes = value.len();
    if bytes > max_bytes {
        Err(format!(
            "{label} is {bytes} UTF-8 bytes; the hard limit is {max_bytes}"
        ))
    } else {
        Ok(())
    }
}

